-- 正本【9】「No.4 昇給率の自己言及の解消」を反映する。
--
-- No.4 昇給率は「自身＋自身以下スタッフの昇給額 ÷ 昇給可能額」で測っていた。
-- しかしこの項目自体が昇給の判定に使われるため、
-- 自分の昇給額が自分の評価を上げ、その評価がまた自分の昇給を決める、という循環になっていた。
-- 正本の指示どおり、分子・分母から本人分を外し、配下スタッフの分だけで測る。
--
-- 計算式（q4_1 ÷ q4_2 × 100）は変わらない。何を数えるかの定義だけが変わる。
--
-- 注意: すでに配布・回答済みのアンケート（form_questions）の文言はここでは変えない。
-- 過去の評価は当時の設問と当時の閾値のまま据え置く（過去評価の不変性）。
-- 次にアンケートを作り直したときから新しい文言が使われる。

UPDATE kpi_questions
SET text = '自身を除く配下スタッフの半期昇給額の合計を入力してください（円）'
WHERE question_key = 'q4_1';

UPDATE kpi_questions
SET text = '自身を除く配下スタッフの半期昇給可能額の合計を入力してください（円）'
WHERE question_key = 'q4_2';

-- なぜ本人分を外すのかを項目マスタにも残す（評価基準の閲覧画面に出す）
UPDATE kpi_items
SET formula_note = '分子・分母とも本人分を除き、配下スタッフの分だけで算出する。'
                || 'この項目自体が昇給の判定に使われるため、本人分を含めると'
                || '「自分の昇給が自分の評価を上げる」循環になるため（正本【9】）。'
WHERE no = 4;
